// tools/build-placements.mjs — bake the zone map onto the model.
//
// Firing 440 probe rays at a 650k-triangle mesh is a second of work. Doing it in the browser
// on every visit, on a phone, is a second nobody should pay for. So we do it here, once, and
// commit the answer. The decals still conform at runtime — DecalGeometry projects onto the
// real mesh — this only fixes where each projector sits and which way it faces.
//
// Re-run whenever model.glb or zones.js changes:  node tools/build-placements.mjs

import fs from 'node:fs';
import { loadGlb, collectTriangles, normalise, Grid, TARGET_LENGTH } from './mesh.mjs';
import { ZONES, PROBE } from '../zones.js';
import { snapZone, v as V } from '../zone-frame.js';

const MODEL = new URL('../model.glb', import.meta.url).pathname;
const OUT = new URL('../placements.js', import.meta.url).pathname;

const glb = loadGlb(MODEL);
const tris = collectTriangles(glb);
const info = normalise(tris);
const grid = new Grid(tris.filter(t => t.mat !== 'Material'), 0.05);
const cast = (o, d, maxT) => grid.raycast(o, d, maxT);

const r = n => Math.round(n * 10000) / 10000;
const rows = [];
let missing = 0;

for (const z of ZONES) {
  const s = snapZone(z, PROBE[z.probe], cast);
  if (!s) { missing++; console.error(`! ${z.id} did not land on the model`); continue; }
  rows.push(`  ${z.id}: { p: [${s.position.map(r).join(', ')}], ` +
            `n: [${s.normal.map(r).join(', ')}], ` +
            `x: [${s.frame.x.map(r).join(', ')}] },`);
}

const src = `// placements.js — GENERATED by tools/build-placements.mjs. Do not edit by hand.
//
// Where each of the 82 zones actually sits on model.glb, measured by probe ray:
//   p  world position of the decal projector
//   n  outward surface normal, plane-fitted across the zone's own footprint
//   x  the decal's local +X in world space — the axis that keeps a row reading square
//
// Regenerate after any change to model.glb or to the row table in zones.js.

/** The viewer reproduces this normalisation so these numbers mean something. */
export const NORMALISE = { targetLength: ${TARGET_LENGTH}, groundMaterial: 'Material' };

export const PLACEMENTS = {
${rows.join('\n')}
};
`;
fs.writeFileSync(OUT, src);
console.log(`wrote placements.js — ${rows.length}/${ZONES.length} zones${missing ? `, ${missing} MISSING` : ''}`);
console.log(`model normalisation: scale ${info.scale.toFixed(5)}, offset [${info.offset.map(v => v.toFixed(4)).join(', ')}]`);
